/** Returns the text for `key` in the current language. Values in `vars` are HTML-escaped unless raw = true. */
function t(key, vars = {}, raw = false) {
  const row = T[key];
  let text = row ? (row[{ en: 0, fr: 1, ar: 2 }[LANG]] || row[0]) : key;
  for (const [name, value] of Object.entries(vars)) {
    const safe = raw ? String(value ?? "") : String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
    text = text.split(`{${name}}`).join(safe);
  }
  return text;
}

/** Fills every element that has a data-i18n / data-i18n-html / data-i18n-ph attribute. */
function translatePage(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}
